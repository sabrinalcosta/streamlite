# GRÁFICO 1 - MÉDIA DE NOTAS POR CATEGORIA DE HORAS DE SONO

import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt

# CRIAÇÃO DAS CATEGORIAS DE HORAS DE SONO
bins = [4, 5, 6, 7, 8, np.inf]
labels = ['4-5 horas', '5-6 horas', '6-7 horas', '7-8 horas', '8+ horas']

df['Categoria_Sono'] = pd.cut(
    df['Horas_de_Sono'],
    bins=bins,
    labels=labels,
    right=False
)

# CÁLCULO DA MÉDIA DE NOTAS POR CATEGORIA DE SONO
media_notas = (
    df.groupby('Categoria_Sono', observed=True)['Notas']
    .mean()
    .reset_index()
)

# CRIAÇÃO DO GRÁFICO
plt.figure(figsize=(8,5))

sns.barplot(
    data=media_notas,
    x='Categoria_Sono',
    y='Notas',
    hue='Categoria_Sono',
    palette='rocket',
    legend=False
)

# PERSONALIZAÇÃO DO GRÁFICO
plt.title('Média de Notas por Categoria de Horas de Sono')
plt.xlabel('Horas de Sono')
plt.ylabel('Média de Notas')
plt.grid(False)

# AJUSTE FINAL
plt.tight_layout()
plt.show()

