import pandas as pd
import matplotlib.pyplot as plt

# Criar faixas de horas de uso
df['faixa_uso'] = pd.cut(
  df['Uso_de_Dispositivo'],
  bins=[0, 2, 4, 6, 9, 12],
  labels=['0-2h', '2-4h', '4-6h', '6-8h', '8h+']
)

# Mapear os níveis de estresse para valores numéricos
stress_mapping = {'Low': 1, 'Medium': 2, 'High': 3}
df['stress_level_numeric'] = df['Nível_de_Estresse'].map(stress_mapping)

# Média do estresse por faixa - adicionando observed=True
dados = df.groupby('faixa_uso', observed=True)['stress_level_numeric'].mean()

plt.figure(figsize=(7,4))
dados.plot(kind='bar', color=['rosybrown', 'palevioletred', 'plum', 'mediumorchid', 'purple'])

plt.title('Horas de uso de dispositivos e nível de estresse')
plt.xlabel('Faixa de horas de uso')
plt.ylabel('Nível médio de estresse')
plt.xticks(rotation=0)

plt.show()

